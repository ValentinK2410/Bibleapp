text = KT.read_text(encoding="utf-8")
ph_block = text.split("private val PHRASES:")[1].split("private val TOKENS:")[0]
to_block = text.split("private val TOKENS:")[1].split("fun fixRussianGloss")[0]

def parse_pairs(block):
    return dict(re.findall(r'"((?:[^"\\]|\\.)+)"\s+to\s+"((?:[^"\\]|\\.)+)"', block))

ph = parse_pairs(ph_block)
to = parse_pairs(to_block)
orig_ph_keys = set(ph.keys())
orig_to_keys = set(to.keys())
allp = {**to, **ph, **EXTRA}  # EXTRA перекрывает старые пары

def bucket(k: str) -> str:
    if k in orig_ph_keys:
        return "ph"
    if k in orig_to_keys:
        return "to"
    if " " in k or "," in k or "<" in k:
        return "ph"
    if len(k) >= 11:
        return "ph"
    return "to"

phrases: dict[str, str] = {}
tokens: dict[str, str] = {}
for k, v in allp.items():
    if bucket(k) == "ph":
        phrases[k] = v
    else:
        tokens[k] = v

ph_sorted = sorted(phrases.items(), key=lambda x: (-len(x[0]), x[0]))
to_sorted = sorted(tokens.items(), key=lambda x: (-len(x[0]), x[0]))

def fmt_pairs(pairs):
    lines = []
    for a, b in pairs:
        a = a.replace("\\", "\\\\").replace('"', '\\"')
        b = b.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'        "{a}" to "{b}",')
    return "\n".join(lines)

new_ph = fmt_pairs(ph_sorted)
new_to = fmt_pairs(to_sorted)

out = text
out = re.sub(
    r"private val PHRASES: List<Pair<String, String>> = listOf\([\s\S]*?\)\.distinctBy",
    f"private val PHRASES: List<Pair<String, String>> = listOf(\n{new_ph}\n    ).distinctBy",
    out,
    count=1,
)
out = re.sub(
    r"private val TOKENS: List<Pair<String, String>> = listOf\([\s\S]*?\)\.distinctBy",
    f"private val TOKENS: List<Pair<String, String>> = listOf(\n{new_to}\n    ).distinctBy",
    out,
    count=1,
)
KT.write_text(out, encoding="utf-8")
