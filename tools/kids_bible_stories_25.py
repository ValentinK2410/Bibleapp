def verse(book: str, chapter: int, number: int) -> str:
    data = json.loads((SYN / f"{book}.json").read_text(encoding="utf-8"))
    chap = next(item for item in data["book"]["chapters"] if item["number"] == chapter)
    return next(item for item in chap["verses"] if item["number"] == number)["text"]


def track(paragraphs, meaning, christ, questions, prayer, activity):
    spoken = paragraphs + [meaning, christ, prayer, activity, *questions]
    for text in spoken:
        if not str(text).strip():
            raise SystemExit("пустая строка")
        if ";" in text:
            raise SystemExit("точка с запятой в устном поле: " + text[:90])
    return {
        "paragraphs": paragraphs,
        "meaning": meaning,
        "christLink": christ,
        "questions": questions,
        "prayer": prayer,
        "activity": activity,
    }


def story(
    *,
    id,
    book,
    title,
    refs,
    kind,
    vbook,
    chapter,
    verse_no,
    vref,
    scenes,
    young,
    mid,
    extra,
    meaning,
    christ,
    questions,
    prayer,
    activity,
    meaning_old=None,
    activity_old=None,
):
    if sum(map(len, young)) >= sum(map(len, mid)):
        raise SystemExit(f"{id}: текст 5–7 не короче 8–10")
    if len(scenes) != len(mid) + 1:
        raise SystemExit(f"{id}: сцен {len(scenes)}, а нужно {len(mid) + 1}")
    young_q = questions[:2]
    images = [f"kids_bible_{id}"] + [f"kids_bible_{id}_s{i}" for i in range(2, len(mid) + 2)]
    return {
        "id": id,
        "bookId": book,
        "order": 1,
        "title": title,
        "refs": refs,
        "kind": kind,
        "keyVerse": verse(vbook, chapter, verse_no),
        "keyVerseRef": vref,
        "art": images[0],
        "images": images,
        "tracks": {
            "5_7": track(young, meaning, christ, young_q, prayer, activity),
            "8_10": track(mid, meaning, christ, questions, prayer, activity),
            "11_13": track(mid + [extra], meaning_old or meaning, christ, questions, prayer, activity_old or activity),
        },
        "_scenes": scenes,
    }


