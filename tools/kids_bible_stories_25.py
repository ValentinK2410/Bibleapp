def ot_stories():
    return []


def ensure_images(story: dict) -> dict:
    if story.get("images"):
        return story
    longest = max(len(story["tracks"][age]["paragraphs"]) for age in ("5_7", "8_10", "11_13"))
    images = [story["art"]] + [f"kids_bible_{story['id']}_s{index}" for index in range(2, longest + 1)]
    out = {}
    for key, value in story.items():
        if key == "tracks":
            out["images"] = images
        out[key] = value
    return out


def scene_prompts(stories: list[dict]) -> list[dict]:
    rows = []
    for story in stories:
        names = story.get("images") or []
        if story["id"] in EXISTING_SCENES:
            texts = [None] + EXISTING_SCENES[story["id"]]
        else:
            texts = story.get("_scenes") or []
        for index, name in enumerate(names):
            webp = DRAW / f"{name}.webp"
            if webp.exists():
                continue
            scene = texts[index] if index < len(texts) and texts[index] else story["title"]
            rows.append({
                "drawable": name,
                "file": f"app/src/main/res/drawable/{name}.webp",
                "storyId": story["id"],
                "prompt": f"{STYLE} Сцена: {scene}",
            })
    return rows


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--part", choices=["nt", "ot", "all"], default="all")
    args = parser.parse_args()
    data = json.loads(STORIES.read_text(encoding="utf-8"))
    before = {item["id"]: json.dumps(item["tracks"], ensure_ascii=False) for item in data["stories"]}
    verses = {item["id"]: item["keyVerse"] for item in data["stories"]}
    data["stories"] = [ensure_images(item) for item in data["stories"]]
    have = {item["id"] for item in data["stories"]}
    batch = []
    if args.part in ("nt", "all"):
        batch += nt_stories()
    if args.part in ("ot", "all"):
        batch += ot_stories()
    for item in batch:
        if item["id"] in have:
            continue
        data["stories"].append({key: value for key, value in item.items() if key != "_scenes"})
        have.add(item["id"])
    for sid, tracks in before.items():
        current = next(item for item in data["stories"] if item["id"] == sid)
        if json.dumps(current["tracks"], ensure_ascii=False) != tracks or current["keyVerse"] != verses[sid]:
            raise SystemExit(f"изменился старый текст: {sid}")
    STORIES.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    # Подсказки собираем заново по всему каталогу, чтобы не потерять сцены новых историй.
    fresh = json.loads(STORIES.read_text(encoding="utf-8"))
    known_scenes = {item["id"]: item.get("_scenes") for item in batch}
    for item in fresh["stories"]:
        if item["id"] in known_scenes:
            item["_scenes"] = known_scenes[item["id"]]
    payload = {
        "style": STYLE,
        "note": "Файлов картинок здесь нет. Первая картинка старых историй уже лежит в drawable. Остальное нужно сгенерировать отдельно.",
        "missing": scene_prompts(fresh["stories"]),
    }
    PROMPTS.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"stories {len(fresh['stories'])}, prompts {len(payload['missing'])}")


if __name__ == "__main__":
    main()

