def build_text_from_words(words):
    parts = []
    for w in words:
        r = w["r"]
        if r != "-":
            parts.append(r.replace("_", " "))
    return " ".join(parts)


def generate_book_json(book_id):
    path = os.path.join(BASE, f"{book_id}.json")
    try:
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
    except (FileNotFoundError, json.JSONDecodeError):
        print(f"  WARNING: {path} not found, skipping")
        return

    book_interlinear = INTERLINEAR_DATA.get(book_id, {})
    existing_chapters = {ch["number"]: ch for ch in data["book"]["chapters"]}

    for ch_num, verses_data in book_interlinear.items():
        if ch_num in existing_chapters:
            ch = existing_chapters[ch_num]
            existing_verses = {v["number"]: v for v in ch["verses"]}
            for v_num, words in verses_data.items():
                text = build_text_from_words(words)
                existing_verses[v_num] = {
                    "number": v_num,
                    "text": text,
                    "words": words,
                }
            ch["verses"] = [existing_verses[k] for k in sorted(existing_verses.keys())]
        else:
            verses = []
            for v_num in sorted(verses_data.keys()):
                words = verses_data[v_num]
                text = build_text_from_words(words)
                verses.append({"number": v_num, "text": text, "words": words})
            existing_chapters[ch_num] = {"number": ch_num, "verses": verses}

    data["book"]["chapters"] = [existing_chapters[k] for k in sorted(existing_chapters.keys())]

    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print(f"  Updated {path}")


