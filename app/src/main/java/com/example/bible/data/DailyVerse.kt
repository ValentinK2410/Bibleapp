    fun forToday(): DailyVerseEntry {
        val cal = Calendar.getInstance()
        val dayOfYear = cal.get(Calendar.DAY_OF_YEAR)
        return verses[dayOfYear % verses.size]
    }

    fun referenceLabel(entry: DailyVerseEntry): String {
        val canon = BibleCanon.byId(entry.bookId)
        val name = canon?.nameRu ?: entry.bookId
        return "$name ${entry.chapter}:${entry.verse}"
