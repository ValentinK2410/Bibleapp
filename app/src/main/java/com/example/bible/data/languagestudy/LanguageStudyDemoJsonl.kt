import org.json.JSONObject

/** Короткая демо-колода: импорт при нулевом количестве слов языка в БД (не заменяет полный пакет). */
object LanguageStudyDemoJsonl {

    fun buildJsonlForLang(langCode: String): String = buildJsonl(entriesFor(langCode))

    private fun buildJsonl(rows: List<DemoWord>): String =
        rows.mapIndexed { idx, w ->
            val id = "${idx + 1}".padStart(4, '0')
            JSONObject().apply {
                put("id", id)
                put("lemma", w.lemma)
                put("display", w.display)
                put("glossRu", w.glossRu)
                put("ipa", w.ipa)
                put("pos", w.pos)
                put("frequencyRank", w.rank)
                w.exL2?.let { put("exampleL2", it) }
                w.exRu?.let { put("exampleRu", it) }
                w.mnem?.takeIf { it.isNotBlank() }?.let { put("mnemonicHint", it) }
                w.morph?.takeIf { it.isNotBlank() }?.let { put("morphologyNotes", it) }
            }.toString()
        }.joinToString("\n")

    private data class DemoWord(
        val lemma: String,
        val display: String,
        val glossRu: String,
        val ipa: String,
        val pos: String,
        val rank: Int,
        val exL2: String? = null,
        val exRu: String? = null,
        val mnem: String? = null,
        val morph: String? = null,
    )

    private fun entriesFor(lang: String): List<DemoWord> = when (lang) {
        "english" -> englishDemo
        "irit" -> hebrewDemo
        "greek" -> greekDemo
        "arabic" -> arabicDemo
        else -> englishDemo
    }

