    private val tokenPatterns: List<Pair<Regex, String>> by lazy {
        TOKENS.map { (from, to) ->
            Regex(Regex.escape(from), RegexOption.IGNORE_CASE) to to
        }
    }

    /** Strong-коды, где «speech» в источнике означает «слово», а не «речь». */
    private val speechAsWordStrongs = setOf("G3056", "H0565", "H4405", "H9002")

    fun fixRussianGloss(raw: String, strong: String = ""): String {
        if (raw.isEmpty()) return raw
        var s = raw
        for ((a, b) in PHRASES) {
            s = s.replace(a, b)
        }
        val speechRu = if (strong in speechAsWordStrongs) "слово" else "речь"
        s = SPEECH_TRANSLIT.replace(s) { match ->
            preserveCaseReplacement(match.value, speechRu)
        }
        for ((pattern, to) in tokenPatterns) {
            s = pattern.replace(s) { match ->
                preserveCaseReplacement(match.value, to)
            }
        }
        return s
    }

    /** Калека «speech» → «спич» из [transliterate_remaining.py] (не «спичлесс»). */
    private val SPEECH_TRANSLIT = Regex("(?i)спич(?![a-zа-яё])")

    private fun preserveCaseReplacement(matched: String, replacement: String): String {
        if (matched.isEmpty() || replacement.isEmpty()) return replacement
        return when {
            matched.all { it.isUpperCase() } -> replacement.uppercase()
            matched.first().isUpperCase() -> replacement.replaceFirstChar { it.uppercaseChar() }
            else -> replacement
        }
    }
