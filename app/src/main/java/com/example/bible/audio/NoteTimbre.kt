package com.example.bible.audio

/** Тембр в разделе «Ноты»: синус — синтез; пианино и смычок — записанные сэмплы ([InstrumentSamplePlayer]). */
enum class NoteTimbre {
    /** Чистый синус (синтез). */
    SINE,

    /** Рояль: записанные сэмплы; при сбое загрузки — запасной синтез в [SineTonePlayer]. */
    PIANO,

    /** Смычок: записи виолончели; при сбое загрузки — запасной синтез. */
    VIOLIN,
}
