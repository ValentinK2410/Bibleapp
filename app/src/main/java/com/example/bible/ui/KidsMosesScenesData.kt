package com.example.bible.ui

import androidx.compose.ui.graphics.Color

/** Вариант ответа в «Диалоге выбора верой» перед ключевым чудом Моисея. */
internal data class MosesFaithOption(
    val text: String,
    val isFaithAnswer: Boolean,
    val feedback: String,
)

/** Диалог выбора верой, который открывается перед главным действием каждой из 6 сцен книги Исход. */
internal data class MosesFaithChoice(
    val sceneNumber: Int,
    val situationTitle: String,
    val situationDescription: String,
    val speakerLabel: String,
    val keyVerseRef: String,
    val keyVerseText: String,
    val deepMeaning: String,
    val ttsText: String,
    val miracleBanner: String,
    val options: List<MosesFaithOption>,
)

/** Описание одной из 6 уникальных сюжетных сцен игры «Путь Моисея». */
internal data class MosesSceneInfo(
    val number: Int,
    val emoji: String,
    val shortTitle: String,
    val fullTitle: String,
    val bibleRef: String,
    val objectiveHint: String,
    val actionEmoji: String,
    val actionLabel: String,
    val skyColors: List<Color>,
    val groundColor: Color,
    val faithChoice: MosesFaithChoice,
)

/** Заповедь Синайского Завета (Исход 20:2–17) для интерактивных Каменных Скрижалей в 6-й сцене. */
internal data class SinaiCommandmentItem(
    val number: Int,
    val roman: String,
    val shortText: String,
    val fullScriptureText: String,
    val tabletNumber: Int, // 1 = Любовь к Богу (1..4), 2 = Любовь к ближнему (5..10)
    val childMeaning: String,
    val ttsText: String,
)

